import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';

import { gitObjectType, LEGACY_PROSE_PROVENANCE, provenanceFindings, withProvenance } from './evidence-gate.mjs';

const commits = () => 'commit';
const generated = (body) => `# Report\n\nGenerated from raw check output by \`scripts/report.mjs\`.\n\n${body}`;
const rules = (findings) => findings.map(({ rule }) => rule);
const PROSE =
  '# Phase 1 — Calibration Gate report\n\nGenerated-from: a revision before `6a0c9c2`, whose byte-budget assertion read a field\n';

test('a generated artefact that names no revision is a finding, because a stale report reads like a fresh one', () => {
  const findings = provenanceFindings([{ path: 'audits/phase-9/REPORT.md', text: generated('Result: PASS') }], commits);
  assert.deepEqual(rules(findings), ['no-provenance']);
});

test('a generated artefact naming its revision passes', () => {
  const findings = provenanceFindings(
    [{ path: 'audits/phase-9/REPORT.md', text: generated('Generated-from: abc1234\n\nResult: PASS') }],
    commits
  );
  assert.deepEqual(findings, []);
});

test('a hand-written document outside audits/ is not asked for provenance', () => {
  assert.deepEqual(provenanceFindings([{ path: 'docs/PRD.md', text: '# PRD\n\nHand written.' }], commits), []);
});

test('every markdown file under audits/ is an artefact, wherever it sits and whatever it says about itself', () => {
  const findings = provenanceFindings(
    [
      { path: 'audits/geo-baseline.md', text: '# GEO baseline\n\nGenerated by `npm run audit:geo` from the build.\n' },
      { path: 'audits/phase-0/BASELINE.md', text: '# Baseline\n\nMedian of 3 runs.\n' },
      { path: 'audits/phase-4.5/adhd/kiss.md', text: '# ADHD branch\n' },
      { path: 'audits/geo-probe.json', text: '{}\n' },
    ],
    commits
  );
  assert.deepEqual(
    findings.map(({ rule, path }) => `${rule} ${path}`),
    [
      'no-provenance audits/geo-baseline.md',
      'no-provenance audits/phase-0/BASELINE.md',
      'no-provenance audits/phase-4.5/adhd/kiss.md',
    ]
  );
});

test('a file under a phase directory that names its revision passes', () => {
  const findings = provenanceFindings(
    [{ path: 'audits/phase-0/BASELINE.md', text: '# Baseline\n\nGenerated-from: 9fd5605\n\nMedian of 3 runs.\n' }],
    commits
  );
  assert.deepEqual(findings, []);
});

test('records nested below a phase directory are covered, at the repo-relative paths the runner supplies', () => {
  const findings = provenanceFindings(
    [
      { path: 'audits/phase-4.5/adhd/kiss.md', text: '# ADHD branch\n' },
      { path: 'audits/phase-4.5/adhd/rival.md', text: '# ADHD branch\n\nGenerated-from: 332b4c7\n' },
    ],
    commits
  );
  assert.deepEqual(
    findings.map(({ path }) => path),
    ['audits/phase-4.5/adhd/kiss.md']
  );
});

test('a provenance line whose first word is not a hash is a finding, so "not-a-revision" no longer passes', () => {
  const findings = provenanceFindings(
    [{ path: 'audits/zz.md', text: '# Z\n\nGenerated-from: not-a-revision\n' }],
    commits
  );
  assert.deepEqual(rules(findings), ['provenance-not-a-hash']);
  assert.match(findings[0].detail, /"not-a-revision"/);
});

test('a hash is 7 to 40 lowercase hexadecimal digits, nothing shorter, longer or otherwise spelt', () => {
  const verdict = (token) =>
    rules(provenanceFindings([{ path: 'audits/zz.md', text: `# Z\n\nGenerated-from: ${token}\n` }], commits));
  for (const token of ['abc123', 'ABC1234', 'abc123g', 'a'.repeat(41), 'v1.0.0'])
    assert.deepEqual(verdict(token), ['provenance-not-a-hash'], token);
  for (const token of ['abc1234', 'a'.repeat(40)]) assert.deepEqual(verdict(token), [], token);
});

test('only the first word is the revision, so a note may follow it', () => {
  const asked = [];
  const objectType = (token) => {
    asked.push(token);
    return 'commit';
  };
  const findings = provenanceFindings(
    [{ path: 'audits/phase-0/BASELINE.md', text: '# B\n\nGenerated-from: 9fd5605 (the template as scaffolded)\n' }],
    objectType
  );
  assert.deepEqual(findings, []);
  assert.deepEqual(asked, ['9fd5605']);
});

test('a hash that names no object in the repository is a finding, so a typo cannot pass for a revision', () => {
  const findings = provenanceFindings(
    [{ path: 'audits/zz.md', text: '# Z\n\nGenerated-from: 0000000\n' }],
    () => undefined
  );
  assert.deepEqual(rules(findings), ['provenance-not-a-commit']);
  assert.match(findings[0].detail, /"0000000" names no object/);
});

test('a hash that names a tag or a tree is a finding that says which, since a pasted release name reads as a tag', () => {
  for (const type of ['tag', 'tree', 'blob']) {
    const findings = provenanceFindings(
      [{ path: 'audits/zz.md', text: '# Z\n\nGenerated-from: abc1234\n' }],
      () => type
    );
    assert.deepEqual(rules(findings), ['provenance-not-a-commit']);
    assert.match(findings[0].detail, new RegExp(`"abc1234" names a ${type}, not a commit`));
  }
});

test('the legacy allow-list is pinned: exactly the eight Calibration Gate reports that predate stamping, each with a reason', () => {
  assert.equal(Object.keys(LEGACY_PROSE_PROVENANCE).length, 8);
  assert.deepEqual(Object.keys(LEGACY_PROSE_PROVENANCE), [
    'audits/phase-1/REPORT.md',
    'audits/phase-2/REPORT.md',
    'audits/phase-3/REPORT.md',
    'audits/phase-4/REPORT.md',
    'audits/phase-4.5/REPORT.md',
    'audits/phase-4.6/REPORT.md',
    'audits/phase-4.7/REPORT.md',
    'audits/phase-5/REPORT.md',
  ]);
  for (const reason of Object.values(LEGACY_PROSE_PROVENANCE)) assert.match(reason, /6a0c9c2/);
  assert.ok(Object.isFrozen(LEGACY_PROSE_PROVENANCE));
});

test('a listed report may keep its prose provenance, and the same prose on any other path is a finding', () => {
  const findings = provenanceFindings(
    [
      { path: 'audits/phase-1/REPORT.md', text: PROSE },
      { path: 'audits/phase-1/copy/REPORT.md', text: PROSE },
      { path: 'audits/phase-5.2/REPORT.md', text: PROSE },
    ],
    commits
  );
  assert.deepEqual(
    findings.map(({ rule, path }) => `${rule} ${path}`),
    ['provenance-not-a-hash audits/phase-1/copy/REPORT.md', 'provenance-not-a-hash audits/phase-5.2/REPORT.md']
  );
});

test('the allow-list excuses prose only: a listed report still needs the line, and a hash on it must name a commit', () => {
  const findings = provenanceFindings(
    [
      { path: 'audits/phase-2/REPORT.md', text: generated('Result: PASS') },
      { path: 'audits/phase-3/REPORT.md', text: generated('Generated-from: 0000000\n') },
    ],
    () => undefined
  );
  assert.deepEqual(rules(findings), ['no-provenance', 'provenance-not-a-commit']);
});

test('the line a generator stamps sits under the title and is the line the gate reads', () => {
  const stamped = withProvenance('# GEO probe\n\nEach row is one buyer prompt.\n', 'abc1234');
  assert.equal(stamped, '# GEO probe\n\nGenerated-from: abc1234\n\nEach row is one buyer prompt.\n');
  assert.deepEqual(provenanceFindings([{ path: 'audits/geo-probe.md', text: stamped }], commits), []);
});

test('git names the type of each object in this repository, and nothing for a hash it does not hold', () => {
  const repo = fileURLToPath(new URL('../..', import.meta.url));
  const git = (...args) => execFileSync('git', args, { cwd: repo, encoding: 'utf8' }).trim();
  const objectType = gitObjectType(repo);
  assert.equal(objectType(git('rev-parse', '--short', 'HEAD')), 'commit');
  assert.equal(objectType(git('rev-parse', 'HEAD^{tree}')), 'tree');
  assert.equal(objectType('0000000'), undefined);
});

test('a missing git stops the gate outright instead of blaming every hash in audits/ for it', () => {
  const path = process.env.PATH;
  process.env.PATH = mkdtempSync(join(tmpdir(), 'no-git-'));
  try {
    assert.throws(() => gitObjectType(fileURLToPath(new URL('.', import.meta.url)))('abc1234'), { code: 'ENOENT' });
  } finally {
    process.env.PATH = path;
  }
});

test('a report that says FAIL is not evidence, however well it names the commit it came from', () => {
  const failing = '# Phase 9 report\n\nGenerated-from: abc1234\n\nResult: FAIL\n';
  const passing = '# Phase 9 report\n\nGenerated-from: abc1234\n\nResult: PASS\n';
  const commit = () => 'commit';

  assert.deepEqual(provenanceFindings([{ path: 'audits/phase-9/REPORT.md', text: passing }], commit), []);
  assert.deepEqual(provenanceFindings([{ path: 'audits/phase-9/REPORT.md', text: failing }], commit), [
    {
      path: 'audits/phase-9/REPORT.md',
      rule: 'failing-report',
      detail: 'reads "Result: FAIL": a report committed as evidence records a run that passed',
    },
  ]);
});
