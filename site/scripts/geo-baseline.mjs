const PROMPT_HEADING = /^\*\*(\d+)\.\s+([^*]+)\*\*$/gm;

const normalise = (value) =>
  value
    .replace(/&#(\d+);/g, (_, code) => String.fromCharCode(Number(code)))
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201c\u201d]/g, '"')
    .replace(/[\u2014\u2013]/g, '-')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();

export function parsePrompts(doc) {
  const start = doc.indexOf('### The 30 buyer prompts');
  const end = doc.indexOf('### GAP register');
  const section = doc.slice(start, end === -1 ? undefined : end);

  const headings = [...section.matchAll(PROMPT_HEADING)].map((match) => ({
    number: Number(match[1]),
    prompt: match[2].trim(),
    at: match.index,
    after: match.index + match[0].length,
  }));

  return headings.map((heading, index) => {
    const nextHeading = headings[index + 1];
    const ownBody = section.slice(heading.after, nextHeading?.at ?? section.length);
    const shared = ownBody.trim() === '' && nextHeading;
    const body = shared ? section.slice(nextHeading.after, headings[index + 2]?.at ?? section.length) : ownBody;

    const mustWinLine = /Must win:\s*([^\n]+)/.exec(body)?.[1] ?? '';
    const routes = [...mustWinLine.matchAll(/`([^`]+)`/g)].map((match) => match[1]);
    return {
      number: heading.number,
      prompt: heading.prompt,
      mustWin: routes[0] ?? '',
      support: routes.slice(1),
      passage: /Passage:\s*"([^"]+)"/.exec(body)?.[1]?.trim() ?? '',
    };
  });
}

export function scorePrompt(prompt, pages) {
  const page = pages[prompt.mustWin] ?? pages[prompt.mustWin.replace(/\/$/, '')];
  if (!page) {
    const detail =
      prompt.mustWin === '' ? 'the core names no must-win route' : `must-win route ${prompt.mustWin} does not build`;
    return { ...prompt, state: 'gap', missing: [detail] };
  }

  const missing = [];
  if (prompt.passage && !normalise(page.text).includes(normalise(prompt.passage))) missing.push('passage');
  if (!page.hasShortAnswer) missing.push('marked citable unit');
  if (!page.hasJsonLd) missing.push('JSON-LD graph');
  if (!page.inLlms) missing.push('llms.txt line');

  return { ...prompt, state: missing.length === 0 ? 'ready' : 'gap', missing };
}

export function renderBaseline(scores) {
  const ready = scores.filter((score) => score.state === 'ready');
  const gaps = scores.filter((score) => score.state !== 'ready');

  return [
    '# GEO baseline — the 30 buyer prompts',
    '',
    'Generated by `npm run audit:geo` from the shipped build. This measures only what the site',
    'controls: does the must-win route exist, does it ship the passage the semantic core promises,',
    'does it carry a marked citable unit (`data-answer` or `data-gate-lead`), a JSON-LD graph and an',
    '`llms.txt` line. A missing marked unit does not mean the page has no answer: it means extraction',
    'has to guess which paragraph is the answer. Whether an engine cites it is checked by hand against',
    'the protocol in `docs/SEMANTIC-CORE.md` and recorded separately.',
    '',
    `On-site readiness: **${ready.length} of ${scores.length}** prompts have everything the site can give.`,
    '',
    '## Ready',
    '',
    ready.length === 0
      ? '_None._'
      : [
          '| # | Prompt | Must win |',
          '|---|---|---|',
          ...ready.map((score) => `| ${score.number} | ${score.prompt} | \`${score.mustWin}\` |`),
        ].join('\n'),
    '',
    '## Gaps',
    '',
    gaps.length === 0
      ? '_None._'
      : [
          '| # | Prompt | Must win | Missing |',
          '|---|---|---|---|',
          ...gaps.map(
            (score) => `| ${score.number} | ${score.prompt} | \`${score.mustWin}\` | ${score.missing.join(', ')} |`
          ),
        ].join('\n'),
    '',
  ].join('\n');
}
