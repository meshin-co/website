export function indexableOnly(rows, noindexRoutes) {
  const excluded = new Set(noindexRoutes);
  return rows.filter((row) => !excluded.has(row.route));
}

export function groupByConcept(findings) {
  const byConcept = new Map();
  for (const finding of findings) {
    const entry = byConcept.get(finding.concept) ?? {
      concept: finding.concept,
      definedBy: finding.definedBy,
      routes: [],
    };
    entry.routes.push(finding.route);
    byConcept.set(finding.concept, entry);
  }
  return [...byConcept.values()].sort(
    (a, b) => b.routes.length - a.routes.length || a.concept.localeCompare(b.concept)
  );
}

export function orphanEntities(entities) {
  return entities.filter((entry) => entry.mentionedBy.length === 0);
}

const table = (header, rows) =>
  rows.length === 0
    ? '_None._'
    : [`| ${header.join(' | ')} |`, `|${header.map(() => '---').join('|')}|`, ...rows].join('\n');

export function renderGaps({ ledger, concepts, orphans, promptGaps }) {
  return [
    '# Phase 4.7 gap analysis',
    '',
    'Generated by `npm run assets:gaps`. Every number below is measured from the shipped build and',
    'the committed content, never estimated. Re-run it after any content change.',
    '',
    '## The ledger',
    '',
    `${ledger.rows} rows, ${ledger.unreviewed} still unreviewed. ${ledger.untraceable} paragraphs ship`,
    `with no source row; ${ledger.dead} source strings reach no page or machine surface. Source:`,
    '`npm run gate:editorial`, ledger at `audits/phase-4.7/inventory.json`.',
    '',
    '## Concepts used without a link to their definition',
    '',
    'Each row is a concept defined on one page and used on others that do not link to it. Not every',
    'mention should become a link — the phase decision is first mention per page. Noindex utility',
    'routes are excluded.',
    '',
    table(
      ['Concept', 'Defined by', 'Routes using it unlinked'],
      concepts.map((entry) => `| ${entry.concept} | \`${entry.definedBy}\` | ${entry.routes.length} |`)
    ),
    '',
    '## Entities nothing points at',
    '',
    'A term with zero inbound mentions is a page the rest of the site never needs, or a concept the',
    'writing avoids using by name.',
    '',
    table(
      ['Entity', 'Owned by'],
      orphans.map((entry) => `| ${entry.entity} | \`${entry.ownedBy}\` |`)
    ),
    '',
    '## Buyer prompts with no owning route',
    '',
    'From the GAP register in `docs/SEMANTIC-CORE.md`. These need owner facts or a new page, so they',
    'stay owner-blocked in this phase.',
    '',
    promptGaps.length === 0 ? '_None._' : promptGaps.map((prompt) => `- ${prompt}`).join('\n'),
    '',
  ].join('\n');
}
