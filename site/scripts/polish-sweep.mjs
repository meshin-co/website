export const WIDTHS = [320, 375, 768, 1024, 1280, 1920];

const OVERFLOW_TOLERANCE = 2;
export const MIN_TARGET = 24;

export function classifyFindings({ route, width, scrollWidth, clientWidth, smallTargets, clipped, duplicateIds }) {
  const findings = [];

  if (scrollWidth - clientWidth > OVERFLOW_TOLERANCE) {
    findings.push({
      route,
      width,
      rule: 'horizontal-overflow',
      detail: `scrollWidth ${scrollWidth} exceeds clientWidth ${clientWidth}`,
    });
  }

  for (const target of smallTargets.filter((target) => target.w < MIN_TARGET || target.h < MIN_TARGET)) {
    findings.push({
      route,
      width,
      rule: 'small-tap-target',
      detail: `${target.label || '(unlabelled)'} is ${Math.round(target.w)}x${Math.round(target.h)}, under ${MIN_TARGET}`,
    });
  }

  for (const element of clipped) {
    findings.push({
      route,
      width,
      rule: 'clipped-text',
      detail: `${element.tag} clips: ${element.text.slice(0, 60)}`,
    });
  }

  for (const id of duplicateIds) {
    findings.push({ route, width, rule: 'duplicate-id', detail: `id "${id}" appears more than once` });
  }

  return findings;
}

export function renderSweep({ routes, widths, findings }) {
  const byRule = findings.reduce(
    (totals, finding) => ({ ...totals, [finding.rule]: (totals[finding.rule] ?? 0) + 1 }),
    {}
  );

  return [
    '# Phase 5 polish sweep',
    '',
    'Generated by `npm run audit:polish` against the shipped build through the gate server.',
    `Swept **${routes} routes** at ${widths.join(', ')} px.`,
    '',
    'Checks: horizontal overflow of the document, interactive targets under 44 px, text clipped by',
    'its own box, and duplicate element ids. Contrast, landmarks and keyboard order are covered by',
    'the axe pass in `npm test` (Playwright) and are not repeated here.',
    '',
    Object.keys(byRule).length === 0
      ? 'No findings.'
      : [
          '| Rule | Count |',
          '|---|---|',
          ...Object.entries(byRule).map(([rule, count]) => `| ${rule} | ${count} |`),
        ].join('\n'),
    '',
    '## Findings',
    '',
    findings.length === 0
      ? '_None._'
      : [
          '| Route | Width | Rule | Detail |',
          '|---|---|---|---|',
          ...findings.map(
            (finding) => `| \`${finding.route}\` | ${finding.width} | ${finding.rule} | ${finding.detail} |`
          ),
        ].join('\n'),
    '',
  ].join('\n');
}
