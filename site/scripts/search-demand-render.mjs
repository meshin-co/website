import { cellText, code, codes, table } from './markdown-table.mjs';

const UNPROVEN = 'unproven';

const percent = (ratio) => `${(ratio * 100).toFixed(1)}%`;
const place = (position) => (position === null ? 'n/a' : position.toFixed(1));

const DEFINITION = [
  'Each row joins one buyer prompt from `docs/SEMANTIC-CORE.md` to what was measured.',
  '',
  'A pair of query and page counts for a prompt when both of these hold:',
  '',
  "- The page is one of the prompt's routes in the core: its must-win route, another must-win route or a support route.",
  '- The query says the same thing as the prompt at a different length. Lowercase both texts, read punctuation as a space and drop function words such as a, the, for, to, how and what; every word of one text must then be in the other.',
  '',
  'Impressions add up over the pairs that count, and position is their mean weighted by impressions.',
  '',
  `A prompt with no pair that counts reads \`${UNPROVEN}\`: no query measured in this window shows demand for it on one of its routes. A page that carried an impression for another query, or for a query Search Console withheld, does not prove a prompt. A prompt whose core entry names no must-win route has nothing to match and always reads \`${UNPROVEN}\`.`,
];

function activityLines({ window, property, totals, firstDay, busiestDay }) {
  if (totals.impressions === 0) {
    return [
      `The window holds no impressions: Search Console returned no rows for ${property} between ${window.startDate} and ${window.endDate}. Every buyer prompt below is ${UNPROVEN}.`,
      '',
    ];
  }
  if (firstDay === null) return [];
  return [
    `First day with an impression in this window: ${firstDay}. Busiest day: ${busiestDay.day}, ${busiestDay.impressions} impressions.`,
    '',
  ];
}

function headerLines(model) {
  const { window, property, totals } = model;
  return [
    `Measured: ${window.measured} (window ${window.startDate} to ${window.endDate})`,
    '',
    `Property: ${property}`,
    '',
    `Totals: ${totals.impressions} impressions, ${totals.clicks} clicks, CTR ${percent(totals.ctr)}, average position ${place(totals.position)}`,
    '',
    ...activityLines(model),
    'Generated by `npm run audit:demand` from the Search Console API. The numbers are web search only. The window ends two days before the day it was measured, so the newest days, which Search Console may not have finished counting, stay out.',
    '',
  ];
}

function queriesSection({ queries, totals, withheld }) {
  const head = ['## Queries', ''];
  if (totals.impressions === 0) return [...head, 'No query produced an impression in this window.', ''];
  const rare = 'Search Console withholds a query that too few people searched';
  if (queries.length === 0) {
    return [...head, `No query is named for these ${totals.impressions} impressions. ${rare}.`, ''];
  }
  const accounted =
    withheld === 0
      ? `all ${totals.impressions} impressions.`
      : `${totals.impressions - withheld} of the ${totals.impressions} impressions. ${rare}; the other ${withheld} impressions belong to such queries.`;
  const rows = queries.map((query) => [
    cellText(query.query),
    String(query.impressions),
    String(query.clicks),
    place(query.position),
    percent(query.ctr),
    codes(query.pages),
    query.prompts.length === 0 ? '-' : query.prompts.join(', '),
  ]);
  return [
    ...head,
    `Queries that produced an impression: ${queries.length}, most impressions first. They account for ${accounted}`,
    '',
    "The Prompts column names the buyer prompts the query proves, by the rule under Buyer prompts below. A dash means the query proves none: no prompt in the core says the same thing, or the page that carried it is not one of that prompt's routes.",
    '',
    table(['Query', 'Impressions', 'Clicks', 'Position', 'CTR', 'Page', 'Prompts'], rows),
    '',
  ];
}

function pagesSection({ pages, pageImpressions, totals }) {
  const head = ['## Pages', ''];
  if (pages.length === 0) return [...head, 'No route carried an impression in this window.', ''];
  const overlap =
    pageImpressions > totals.impressions
      ? ` These rows add up to ${pageImpressions} impressions against a total of ${totals.impressions}, because one results page can show more than one page of the site and each page counts the impression.`
      : '';
  const rows = pages.map((page) => [
    code(page.route),
    String(page.impressions),
    String(page.clicks),
    place(page.position),
    percent(page.ctr),
  ]);
  return [
    ...head,
    `Routes that carried an impression: ${pages.length}, most impressions first. A scheme or host variant of one route is merged into it.${overlap}`,
    '',
    table(['Page', 'Impressions', 'Clicks', 'Position', 'CTR'], rows),
    '',
  ];
}

function daysSection({ days }) {
  const head = ['## By day', ''];
  if (days.length === 0) return [...head, 'No day in this window had an impression.', ''];
  const rows = days.map((day) => [day.day, String(day.impressions), String(day.clicks), place(day.position)]);
  return [
    ...head,
    'Days with at least one impression, oldest first.',
    '',
    table(['Day', 'Impressions', 'Clicks', 'Position'], rows),
    '',
  ];
}

function promptsSection({ prompts }) {
  const proven = prompts.filter(({ impressions }) => impressions > 0).length;
  const rows = prompts.map(({ number, prompt, mustWin, impressions, position, carriedBy }) => [
    String(number),
    cellText(prompt),
    mustWin ? code(mustWin) : '-',
    impressions === 0 ? UNPROVEN : String(impressions),
    impressions === 0 ? '-' : place(position),
    codes(carriedBy),
  ]);
  return [
    '## Buyer prompts',
    '',
    ...DEFINITION,
    '',
    `${proven} of ${prompts.length} prompts have an impression in this window; ${prompts.length - proven} are ${UNPROVEN}.`,
    '',
    table(['#', 'Prompt', 'Must win', 'Impressions', 'Position', 'Carried by'], rows),
    '',
  ];
}

export function renderDemand(model) {
  return [
    '# Search demand: what Search Console measured',
    '',
    ...headerLines(model),
    ...queriesSection(model),
    ...pagesSection(model),
    ...daysSection(model),
    ...promptsSection(model),
  ].join('\n');
}
