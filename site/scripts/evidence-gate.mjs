import { readFileSync } from 'node:fs';

const PROVENANCE = /^Generated-from: (.+)$/m;
const GENERATED_BY = /Generated from raw check output|generated by `?scripts\//i;

export function provenanceFindings(artefacts) {
  return artefacts.flatMap(({ path, text }) => {
    if (!GENERATED_BY.test(text)) return [];
    const provenance = PROVENANCE.exec(text)?.[1]?.trim();
    if (!provenance)
      return [
        { path, rule: 'no-provenance', detail: 'a generated artefact must name the revision it was generated from' },
      ];
    return [];
  });
}

export function readArtefacts(paths) {
  return paths.map((path) => ({ path, text: readFileSync(path, 'utf8') }));
}
