const PURPOSE_HEADING = '## Purpose';
const REQUIREMENTS_HEADING = '## Requirements';
const REQUIREMENT_PREFIX = '### Requirement: ';
const LOCKED_ROW = /\bL(\d{1,3})\b/g;

const BUILT_BYTE_SURFACE = [
  'site/src/',
  'site/public/',
  'site/scripts/',
  'site/astro.config.ts',
  'site/budgets.json',
  'site/lighthouserc.cjs',
  'site/package.json',
  'site/package-lock.json',
];

const nonBlankLines = (text) =>
  text
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean);

export function changedFiles({ git, range }) {
  if (range) return nonBlankLines(git(['diff', '--name-only', range]));
  const base = git(['merge-base', 'HEAD', 'origin/main']).trim();
  const committed = base ? nonBlankLines(git(['diff', '--name-only', `${base}..HEAD`])) : [];
  const working = nonBlankLines(git(['diff', '--name-only', 'HEAD']));
  const untracked = nonBlankLines(git(['ls-files', '--others', '--exclude-standard']));
  return [...new Set([...committed, ...working, ...untracked])];
}

const firstSentence = (text) => {
  const match = text.match(/^.*?[.!?](?=\s|$)/s);
  return (match ? match[0] : text).trim();
};

export function parseSpec(text) {
  const lines = text.split('\n');
  const purposeStart = lines.indexOf(PURPOSE_HEADING);
  const requirementsStart = lines.indexOf(REQUIREMENTS_HEADING);
  const purposeBody = lines
    .slice(purposeStart + 1, requirementsStart === -1 ? undefined : requirementsStart)
    .join(' ')
    .trim();
  const requirements = lines
    .filter((line) => line.startsWith(REQUIREMENT_PREFIX))
    .map((line) => line.slice(REQUIREMENT_PREFIX.length).trim());
  const lockedRows = [...new Set((text.match(LOCKED_ROW) ?? []).map((row) => row.toUpperCase()))];
  return { purpose: firstSentence(purposeBody), requirements, lockedRows };
}

export function censusFromSpecs(specs) {
  const census = {};
  for (const spec of specs) census[spec.capability] = [...spec.requirements].sort();
  return census;
}

export function censusFindings(committed, walked) {
  const findings = [];
  for (const capability of Object.keys(committed)) {
    if (!(capability in walked)) {
      findings.push(`census-missing ${capability}: committed but absent from the tree`);
      continue;
    }
    const before = committed[capability].join(' | ');
    const after = [...walked[capability]].sort().join(' | ');
    if (before !== after)
      findings.push(`census-drift ${capability}: requirement names differ from the committed census`);
  }
  for (const capability of Object.keys(walked)) {
    if (!(capability in committed))
      findings.push(`census-unrecorded ${capability}: in the tree but absent from the census`);
  }
  return findings;
}

export function indexFromSpecs(specs) {
  const rows = [...specs]
    .sort((a, b) => a.capability.localeCompare(b.capability))
    .map((spec) => `- [${spec.capability}](specs/${spec.capability}/spec.md) \u2014 ${spec.purpose}`);
  return [
    '# Capability index',
    '',
    'Generated by `npm run assets:spec-index`. One line per capability, taken from its own Purpose.',
    '',
    ...rows,
    '',
  ].join('\n');
}

export function vacuityFindings({ cliSpecs, walkedSpecs, items }) {
  const findings = [];
  if (items === 0) findings.push('spec-vacuous: the validator reported zero items, so nothing was checked');
  if (cliSpecs !== walkedSpecs) {
    findings.push(`spec-count-disagreement: the validator sees ${cliSpecs} specs, the tree holds ${walkedSpecs}`);
  }
  return findings;
}

export function changeNameFindings(active, archived) {
  const findings = [];
  const prefixes = new Map();
  for (const name of active) {
    const match = name.match(/^(\d+)-[a-z0-9]+(-[a-z0-9]+)*$/);
    if (!match) {
      findings.push(`change-name ${name}: an active change is named NN-slug in lower case`);
      continue;
    }
    const prefix = Number(match[1]);
    if (prefix < 10) findings.push(`change-prefix ${name}: prefixes below 10 collide with the audits/phase-N buckets`);
    if (prefixes.has(prefix))
      findings.push(`change-prefix ${name}: prefix ${prefix} already belongs to ${prefixes.get(prefix)}`);
    prefixes.set(prefix, name);
  }
  for (const name of archived) {
    if (!/^\d{4}-\d{2}-\d{2}-\d+-[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) {
      findings.push(`archive-name ${name}: an archived change is named YYYY-MM-DD-NN-slug`);
    }
  }
  return findings;
}

export function tasksFindings(changes) {
  return changes
    .filter((change) => !change.hasTasks)
    .map((change) => `change-without-tasks ${change.name}: an active change carries tasks.md`);
}

export function skipSpecsFindings(changes) {
  return changes
    .filter((change) => change.skipSpecs && !change.archived)
    .map((change) => `skip-specs-active ${change.name}: the validation opt-out belongs to the archive`);
}

export function singleActiveFindings(changes) {
  const unblocked = changes.filter((change) => !change.blocked || change.ticked > 0);
  if (unblocked.length <= 1) return [];
  const names = unblocked.map((change) => change.name).join(', ');
  return [`two-active-changes: ${names} are all in flight; one at a time unless a change is blocked and untouched`];
}

export function builtByteFiles(changed) {
  return changed.filter((file) => BUILT_BYTE_SURFACE.some((prefix) => file === prefix || file.startsWith(prefix)));
}

export function calibrationFindings({ changed, changes }) {
  if (changed.length === 0) {
    return changes.length === 0
      ? []
      : [
          'calibration-input-empty: no files in the range, so the calibration rule judged nothing while a change is in flight',
        ];
  }
  const built = builtByteFiles(changed);
  if (built.length === 0) return [];
  return changes
    .filter((change) => !change.calibration)
    .map(
      (change) =>
        `change-without-calibration ${change.name}: ${built.length} built-byte files changed, so a Calibration Gate task group is owed`
    );
}

export function lockedRowFindings(specs, knownRows) {
  const findings = [];
  const owners = new Map();
  for (const spec of specs) {
    for (const row of spec.lockedRows ?? []) {
      if (!knownRows.has(row)) {
        findings.push(`locked-row-missing ${spec.capability}: ${row} is not a row in the locked decisions`);
        continue;
      }
      if (owners.has(row))
        findings.push(`locked-row-shared ${row}: claimed by ${owners.get(row)} and ${spec.capability}`);
      else owners.set(row, spec.capability);
    }
  }
  return findings;
}

export function summaryLine({ specs, requirements, active, archived, calibration, findings }) {
  return `spec: ${specs} specs, ${requirements} requirements, ${active} active, ${archived} archived, calibration ${calibration}, ${findings} findings`;
}
